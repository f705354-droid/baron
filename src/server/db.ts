export class BaronDatabase {
  private filePath: string;
  public state: DatabaseSchema;

  constructor(customPath?: string) {
    this.filePath = path.resolve(
      process.cwd(),
      customPath || process.env.BARON_DB_PATH || './data/baron-nexus-db.json'
    );
    this.state = this.loadOrInitialize();
  }

  private loadOrInitialize(): DatabaseSchema {
    try {
      if (fs.existsSync(this.filePath)) {
        const raw = fs.readFileSync(this.filePath, 'utf-8');
        const parsed = JSON.parse(raw) as DatabaseSchema;
        if (parsed && Array.isArray(parsed.projects) && Array.isArray(parsed.users)) {
          return parsed;
        }
      }
    } catch {
      // Fall through to seed initialization
    }
    const seeded = createInitialSeedData();
    this.save(seeded);
    return seeded;
  }

  public save(nextState: DatabaseSchema = this.state): void {
    this.state = nextState;
    try {
      const dir = path.dirname(this.filePath);
      if (!fs.existsSync(dir)) {
        fs.mkdirSync(dir, { recursive: true });
      }
      const tmpPath = `${this.filePath}.tmp`;
      fs.writeFileSync(tmpPath, JSON.stringify(this.state, null, 2), 'utf-8');
      fs.renameSync(tmpPath, this.filePath);
    } catch {
      // In read-only environments, in-memory state remains authoritative
    }
  }

  public recordAudit(params: {
    actor: User;
    projectId: string;
    action: string;
    targetType: string;
    targetId: string;
    outcome: AuditEvent['outcome'];
    details?: Record<string, unknown>;
  }): AuditEvent {
    const latest = this.state.auditEvents[0];
    const prevHash = latest ? latest.chainHash : 'GENESIS_BARON_NEXUS_0000000000000000';
    const baseEvent: Omit<AuditEvent, 'chainHash'> = {
      id: `aud-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
      timestamp: new Date().toISOString(),
      actorId: params.actor.id,
      actorName: params.actor.displayName,
      actorRole: params.actor.role,
      projectId: params.projectId,
      action: params.action,
      targetType: params.targetType,
      targetId: params.targetId,
      outcome: params.outcome,
      details: redactSecrets(params.details || {}),
      prevHash,
    };
    const chainHash = computeAuditHash(baseEvent, prevHash);
    const fullEvent: AuditEvent = { ...baseEvent, chainHash };
    this.state.auditEvents.unshift(fullEvent);
    this.save();
    return fullEvent;
  }

  public resetToDefaultSeed(actor: User): void {
    this.state = createInitialSeedData();
    this.recordAudit({
      actor,
      projectId: 'prj-prod-core',
      action: 'DEMO_DATASET_RESET',
      targetType: 'Database',
      targetId: 'global',
      outcome: 'SUCCESS',
      details: { message: 'Reset database to synthetic demonstration dataset.' },
    });
  }

  public purgeSyntheticData(actor: User): { purgedCounts: Record<string, number> } {
    const purgedCounts = {
      assets: this.state.assets.filter((a) => a.isSynthetic).length,
      assessments: this.state.assessments.filter((j) => j.isSynthetic).length,
      findings: this.state.findings.filter((f) => f.isSynthetic).length,
      evidence: this.state.evidence.filter((e) => e.isSynthetic).length,
      indicators: this.state.threatIndicators.filter((i) => i.isSynthetic).length,
      alerts: this.state.alerts.filter((a) => a.isSynthetic).length,
      incidents: this.state.incidents.filter((i) => i.isSynthetic).length,
    };

    this.state.assets = this.state.assets.filter((a) => !a.isSynthetic);
    this.state.assessments = this.state.assessments.filter((j) => !j.isSynthetic);
    this.state.findings = this.state.findings.filter((f) => !f.isSynthetic);
    this.state.evidence = this.state.evidence.filter((e) => !e.isSynthetic);
    this.state.threatIndicators = this.state.threatIndicators.filter((i) => !i.isSynthetic);
    this.state.alerts = this.state.alerts.filter((a) => !a.isSynthetic);
    this.state.incidents = this.state.incidents.filter((i) => !i.isSynthetic);
    this.state.cloudChecks = this.state.cloudChecks.filter((c) => !c.isSynthetic);
    this.state.webApiChecks = this.state.webApiChecks.filter((w) => !w.isSynthetic);

    this.recordAudit({
      actor,
      projectId: 'global',
      action: 'SYNTHETIC_DATA_PURGED',
      targetType: 'Database',
      targetId: 'global',
      outcome: 'SUCCESS',
      details: purgedCounts,
    });
    this.save();
    return { purgedCounts };
  }
}
